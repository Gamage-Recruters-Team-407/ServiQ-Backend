const mongoose = require("mongoose");
const ServiceCategory = require("../models/ServiceCategory");
const Service = require("../models/Service");
const { CATEGORY_STATUSES, SERVICE_STATUSES } = require("../constants/enums");

const httpError = (statusCode, message, details) =>
  Object.assign(new Error(message), { statusCode, details });
const isId = (v) => mongoose.isValidObjectId(v);
const escapeRegex = (s = "") => String(s).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

// parent = "root" | <categoryId>
async function listCategories({ status = CATEGORY_STATUSES.ACTIVE, parent, q } = {}) {
  const filter = {};
  if (status !== "all") {
    if (!Object.values(CATEGORY_STATUSES).includes(status)) {
      throw httpError(400, "Invalid status filter");
    }
    filter.status = status;
  }
  if (parent === "root") filter.parent_category_id = null;
  else if (parent) {
    if (!isId(parent)) throw httpError(400, "Invalid parent category id");
    filter.parent_category_id = parent;
  }
  if (q) filter.name = { $regex: escapeRegex(q), $options: "i" };
  return ServiceCategory.find(filter).sort({ name: 1 }).lean();
}

// { "<categoryId>": activeServiceCount }
async function getActiveServiceCounts() {
  const rows = await Service.aggregate([
    { $match: { status: SERVICE_STATUSES.ACTIVE } },
    { $group: { _id: "$category_id", count: { $sum: 1 } } },
  ]);
  return Object.fromEntries(rows.map((r) => [String(r._id), r.count]));
}

async function getCategory(idOrSlug) {
  if (!idOrSlug) return null;
  const filter = isId(idOrSlug) ? { _id: idOrSlug } : { slug: String(idOrSlug).toLowerCase() };
  return ServiceCategory.findOne(filter).lean();
}

function pickFields(body = {}) {
  const out = {};
  for (const k of ["name", "description", "status", "icon_url", "image_url"]) {
    if (body[k] !== undefined) out[k] = body[k];
  }
  if (body.parent_category_id !== undefined) out.parent_category_id = body.parent_category_id || null;
  return out;
}

async function assertParentValid(parentId, selfId) {
  if (!parentId) return;
  if (!isId(parentId)) throw httpError(400, "Invalid parent category id");
  if (selfId && String(parentId) === String(selfId)) {
    throw httpError(400, "A category cannot be its own parent");
  }
  const parent = await ServiceCategory.findById(parentId).lean();
  if (!parent) throw httpError(404, "Parent category not found");
  if (parent.parent_category_id) throw httpError(400, "Only one level of sub-categories is supported");
}

async function createCategory(body) {
  const fields = pickFields(body);
  if (!fields.name || !String(fields.name).trim()) {
    throw httpError(400, "Category name is required", { name: "Category name is required" });
  }
  await assertParentValid(fields.parent_category_id);
  const doc = await ServiceCategory.create(fields); // slug is generated by the model
  return doc.toObject();
}

async function updateCategory(id, body) {
  if (!isId(id)) throw httpError(400, "Invalid category id");
  const fields = pickFields(body);
  if (fields.parent_category_id !== undefined) await assertParentValid(fields.parent_category_id, id);
  const updated = await ServiceCategory.findByIdAndUpdate(id, fields, {
    new: true,
    runValidators: true,
  }).lean();
  if (!updated) throw httpError(404, "Category not found");
  return updated;
}

module.exports = {
  listCategories,
  getActiveServiceCounts,
  getCategory,
  createCategory,
  updateCategory,
};